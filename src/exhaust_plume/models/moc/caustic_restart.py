class MocCausticFamilyRestartStatus(str, Enum):
  """Outcome of the open new-family boundary restart."""

  CONVERGED_OPEN_BOUNDARY = 'converged_open_caustic_family_boundary'
  INVALID_INPUT = 'invalid_input'
  SEED_FAILURE = 'caustic_seed_failure'
  CENTERLINE_FAILURE = 'caustic_restart_centerline_failure'
  AMBIENT_BOUNDARY_FAILURE = 'caustic_restart_ambient_boundary_failure'
  BAND_FAILURE = 'caustic_restart_family_band_failure'


class MocCausticFamilyBandStatus(str, Enum):
  """Outcome of the connected two-triangle restart-band assembly."""

  CONVERGED_OPEN_BAND = 'converged_open_caustic_family_band'
  INVALID_INPUT = 'invalid_input'
  GEOMETRY_FAILURE = 'caustic_family_band_geometry_failure'
  TOPOLOGY_FAILURE = 'caustic_family_band_topology_failure'


@dataclass(frozen=True, slots=True)
class MocCausticFamilyBandResult:
  """A connected open band generated by one-sided caustic continuation.

  Each continuation step is split along its incoming C- diagonal into a
  centerline-side triangle and an ambient-boundary-side triangle.  The band
  is a numerical characteristic patch, not a shock cell: its input and output
  edges remain explicit open seams and no downstream entropy jump is implied.
  """

  status: MocCausticFamilyBandStatus
  centerline_states: tuple[CharacteristicState, ...]
  boundary_states: tuple[CharacteristicState, ...]
  total_pressure_Pa: float
  cells: tuple[MocCharacteristicCell, ...]
  topology: MocTopologyResult
  input_edge_points_m: tuple[tuple[float, float], ...]
  output_edge_points_m: tuple[tuple[float, float], ...]
  maximum_absolute_geometry_residual_m: float | None
  maximum_absolute_invariant_residual: float | None
  message: str = ''
  anchor_point_m: tuple[float, float] | None = None
  anchor_state: CharacteristicState | None = None
  anchor_to_input_min_forward_progress_m: float | None = None

  def __post_init__(self) -> None:
    if (self.anchor_point_m is None) != (self.anchor_state is None):
      raise ValueError(
        'caustic family band anchor point and state must be supplied together'
      )
    if self.anchor_point_m is not None:
      if len(self.anchor_point_m) != 2 or not all(
        isfinite(float(value)) for value in self.anchor_point_m
      ):
        raise ValueError('caustic family band anchor point must be finite')
      assert self.anchor_state is not None
      if not isinstance(self.anchor_state, CharacteristicState):
        raise TypeError(
          'caustic family band anchor state must be a CharacteristicState'
        )
      if (
        abs(self.anchor_state.x_m - float(self.anchor_point_m[0])) > 1.0e-10
        or abs(self.anchor_state.y_m - float(self.anchor_point_m[1])) > 1.0e-10
      ):
        raise ValueError(
          'caustic family band anchor state must lie on its anchor point'
        )
    if self.anchor_to_input_min_forward_progress_m is not None and not isfinite(
      float(self.anchor_to_input_min_forward_progress_m)
    ):
      raise ValueError(
        'caustic family band anchor progress must be finite when supplied'
      )

  @property
  def converged(self) -> bool:
    return self.status is MocCausticFamilyBandStatus.CONVERGED_OPEN_BAND

  @property
  def physical_closure_verified(self) -> bool:
    """The band has no shock or downstream physical termination."""

    return False

  @property
  def chain_promotion_blocked(self) -> bool:
    return True

  @property
  def anchor_wedge_verified(self) -> bool:
    """Whether the selected seed anchor is part of the assembled band."""

    if (
      not self.converged
      or self.anchor_point_m is None
      or self.anchor_state is None
      or len(self.centerline_states) < 1
      or len(self.boundary_states) < 1
    ):
      return False
    expected_vertices = (
      self.anchor_point_m,
      (self.centerline_states[0].x_m, self.centerline_states[0].y_m),
      (self.boundary_states[0].x_m, self.boundary_states[0].y_m),
    )
    for cell in self.cells:
      if cell.cell_kind != 'caustic-restart-anchor-wedge':
        continue
      if len(cell.vertices_xr_m) != len(expected_vertices):
        continue
      if all(
        abs(actual - expected) <= 1.0e-10
        for actual_point, expected_point in zip(
          cell.vertices_xr_m,
          expected_vertices,
          strict=True,
        )
        for actual, expected in zip(actual_point, expected_point, strict=True)
      ):
        return True
    return False

  @property
  def caustic_handoff_verified(self) -> bool:
    """Whether the band retains an exact one-sided caustic anchor."""

    if (
      not self.converged
      or self.anchor_point_m is None
      or self.anchor_state is None
      or self.anchor_to_input_min_forward_progress_m is None
      or len(self.input_edge_points_m) != 2
      or len(self.centerline_states) < 2
      or len(self.boundary_states) < 2
      or not self.anchor_wedge_verified
    ):
      return False
    if any(
      len(point) != 2
      or any(not isfinite(float(value)) for value in point)
      for point in self.input_edge_points_m
    ):
      return False
    expected_input_edge = (
      (self.centerline_states[0].x_m, self.centerline_states[0].y_m),
      (self.boundary_states[0].x_m, self.boundary_states[0].y_m),
    )
    if any(
      abs(actual - expected) > 1.0e-10
      for actual_point, expected_point in zip(
        self.input_edge_points_m,
        expected_input_edge,
        strict=True,
      )
      for actual, expected in zip(actual_point, expected_point, strict=True)
    ):
      return False
    actual_progress = min(
      point[0] - self.anchor_point_m[0] for point in self.input_edge_points_m
    )
    if (
      actual_progress <= 0.0
      or abs(actual_progress - self.anchor_to_input_min_forward_progress_m)
      > 1.0e-10
    ):
      return False
    return all(
      state.x_m > self.anchor_point_m[0]
      for state in (*self.centerline_states, *self.boundary_states)
    )

  def as_chain_termination_decision(self) -> MocChainTerminationDecision:
    """Return the explicit non-physical stop at the open band outlet."""

    if not self.converged:
      raise ValueError(
        'a caustic family chain stop requires a converged open family band'
      )
    return MocChainTerminationDecision(
      physical_termination=False,
      reason=MocChainTerminationReason.OPEN_PHYSICAL_CLOSURE,
      message=(
        'caustic family band is numerically connected but has no fitted shock '
        'or entropy closure for continued-cell promotion'
      ),
      diagnostics={
        'termination_model': 'caustic-family-open-band',
        'cell_count': self.cell_count,
        'step_count': self.step_count,
        'input_edge_points_m': self.input_edge_points_m,
        'output_edge_points_m': self.output_edge_points_m,
        'topology_status': self.topology.status.value,
        'topology_forms_closed_zone': self.topology.forms_closed_zone,
      },
    )

  @property
  def cell_count(self) -> int:
    return len(self.cells)

  @property
  def step_count(self) -> int:
    return max(0, min(len(self.centerline_states), len(self.boundary_states)) - 1)

  def state_at(
    self,
    point_m: tuple[float, float],
    *,
    position_tolerance_m: float = 1.0e-10,
  ) -> CharacteristicState | None:
    """Sample inside the band without extrapolating beyond its triangles."""

    if len(point_m) != 2 or not all(isfinite(float(value)) for value in point_m):
      raise ValueError('point_m must contain two finite coordinates')
    if not isfinite(float(position_tolerance_m)) or position_tolerance_m <= 0.0:
      raise ValueError('position_tolerance_m must be finite and positive')
    point = (float(point_m[0]), float(point_m[1]))
    for cell in self.cells:
      if len(cell.vertices_xr_m) != 3:
        continue
      if cell.cell_kind == 'caustic-restart-anchor-wedge':
        if (
          self.anchor_state is None
          or not self.centerline_states
          or not self.boundary_states
        ):
          continue
        states = (
          self.anchor_state,
          self.centerline_states[0],
          self.boundary_states[0],
        )
      else:
        step = cell.cell_index // 2 + 1
        if step >= len(self.centerline_states) or step >= len(self.boundary_states):
          continue
        if cell.cell_index % 2 == 0:
          states = (
            self.centerline_states[step - 1],
            self.boundary_states[step - 1],
            self.centerline_states[step],
          )
        else:
          states = (
            self.centerline_states[step],
            self.boundary_states[step - 1],
            self.boundary_states[step],
          )
      weights = _triangle_interpolation_weights(
        point,
        cell.vertices_xr_m,
        tolerance_m=position_tolerance_m,
      )
      if weights is None:
        continue
      theta = sum(
        weight * state.theta_rad
        for weight, state in zip(weights, states, strict=True)
      )
      nu = sum(
        weight * state.nu_rad
        for weight, state in zip(weights, states, strict=True)
      )
      inverse = inverse_prandtl_meyer_angle_rad(nu, states[0].gamma)
      if not inverse.converged or inverse.value is None:
        return None
      return CharacteristicState(
        x_m=point[0],
        y_m=point[1],
        theta_rad=theta,
        mach=inverse.value,
        gamma=states[0].gamma,
      )
    return None

  def static_pressure_at(
    self,
    point_m: tuple[float, float],
    *,
    position_tolerance_m: float = 1.0e-10,
  ) -> float | None:
    """Return pressure for an in-band state, or ``None`` outside the band."""

    state = self.state_at(point_m, position_tolerance_m=position_tolerance_m)
    if state is None:
      return None
    pressure_ratio = (
      1.0 + 0.5 * (state.gamma - 1.0) * state.mach * state.mach
    ) ** (state.gamma / (state.gamma - 1.0))
    return self.total_pressure_Pa / pressure_ratio

  def as_report(self) -> dict[str, object]:
    return {
      'status': self.status.value,
      'converged': self.converged,
      'physical_closure_verified': self.physical_closure_verified,
      'chain_promotion_blocked': self.chain_promotion_blocked,
      'anchor_wedge_verified': self.anchor_wedge_verified,
      'caustic_handoff_verified': self.caustic_handoff_verified,
      'band_kind': 'centerline-ambient-two-triangle-characteristic-band',
      'centerline_sample_count': len(self.centerline_states),
      'boundary_sample_count': len(self.boundary_states),
      'total_pressure_Pa': self.total_pressure_Pa,
      'step_count': self.step_count,
      'cell_count': self.cell_count,
      'input_edge_points_m': [list(point) for point in self.input_edge_points_m],
      'output_edge_points_m': [list(point) for point in self.output_edge_points_m],
      'anchor_point_m': self.anchor_point_m,
      'anchor_state': (
        None
        if self.anchor_state is None
        else {
          'x_m': self.anchor_state.x_m,
          'y_m': self.anchor_state.y_m,
          'theta_rad': self.anchor_state.theta_rad,
          'mach': self.anchor_state.mach,
          'gamma': self.anchor_state.gamma,
        }
      ),
      'anchor_to_input_min_forward_progress_m': (
        self.anchor_to_input_min_forward_progress_m
      ),
      'topology': {
        'status': self.topology.status.value,
        'connected': self.topology.connected,
        'forms_closed_zone': self.topology.forms_closed_zone,
        'boundary_component_count': self.topology.boundary_component_count,
        'boundary_edge_count': self.topology.boundary_edge_count,
        'nonmanifold_edge_count': self.topology.nonmanifold_edge_count,
      },
      'maximum_absolute_geometry_residual_m': self.maximum_absolute_geometry_residual_m,
      'maximum_absolute_invariant_residual': self.maximum_absolute_invariant_residual,
      'chain_termination_decision': (
        None
        if not self.converged
        else self.as_chain_termination_decision().as_report()
      ),
      'message': self.message,
    }


@dataclass(frozen=True, slots=True)
class MocCausticFamilyRestartResult:
  """An open, one-sided new-family boundary after a characteristic caustic."""

  status: MocCausticFamilyRestartStatus
  seed: MocSourceStripCausticShockSeedResult | None
  anchor_edge_index: int | None
  anchor_point_m: tuple[float, float] | None
  anchor_state: CharacteristicState | None
  centerline_states: tuple[CharacteristicState, ...]
  boundary_states: tuple[CharacteristicState, ...]
  boundary_points_m: tuple[tuple[float, float], ...]
  total_pressure_Pa: float | None
  ambient_pressure_Pa: float | None
  maximum_absolute_pressure_residual: float | None
  maximum_absolute_tangent_residual: float | None
  maximum_absolute_geometry_residual_m: float | None
  minimum_forward_progress_m: float | None
  source_strip: MocSourceCharacteristicStripResult | None
  family_band: MocCausticFamilyBandResult | None = None
  message: str = ''

  @property
  def converged(self) -> bool:
    return self.status is MocCausticFamilyRestartStatus.CONVERGED_OPEN_BOUNDARY

  @property
  def physical_closure_verified(self) -> bool:
    """The restart has no downstream shock or closed characteristic mesh."""

    return False

  @property
  def chain_promotion_blocked(self) -> bool:
    return True

  @property
  def caustic_handoff_verified(self) -> bool:
    """Whether the selected one-sided seed reaches the new-family band."""

    if (
      not self.converged
      or self.seed is None
      or not self.seed.converged
      or self.anchor_edge_index not in (0, 1)
      or self.anchor_point_m is None
      or self.anchor_state is None
      or self.family_band is None
      or not self.family_band.caustic_handoff_verified
      or self.family_band.anchor_point_m is None
      or self.family_band.anchor_state is None
    ):
      return False
    selected_edge = self.seed.edge_states[self.anchor_edge_index]
    if selected_edge.state is None or selected_edge.point_m is None:
      return False
    return bool(
      self.family_band.anchor_point_m == self.anchor_point_m
      and self.family_band.anchor_state == self.anchor_state
      and selected_edge.point_m == self.anchor_point_m
      and selected_edge.state == self.anchor_state
    )

  def as_chain_termination_decision(self) -> MocChainTerminationDecision:
    """Expose the unresolved old-family/new-family caustic handoff."""

    if not self.caustic_handoff_verified:
      raise ValueError(
        'a caustic restart chain decision requires an exact one-sided '
        'handoff into a converged open family band'
      )
    assert self.seed is not None
    assert self.family_band is not None
    assert self.anchor_point_m is not None
    return MocChainTerminationDecision(
      physical_termination=False,
      reason=MocChainTerminationReason.CHARACTERISTIC_CAUSTIC,
      message=(
        'one-sided caustic handoff reached a new-family open band, but the '
        'old-family bridge and shock/entropy closure remain unresolved'
      ),
      diagnostics={
        'termination_model': 'caustic-new-family-open-handoff',
        'anchor_edge_index': self.anchor_edge_index,
        'anchor_point_m': self.anchor_point_m,
        'family_band_input_edge_points_m': self.family_band.input_edge_points_m,
        'family_band_output_edge_points_m': self.family_band.output_edge_points_m,
        'family_band_cell_count': self.family_band.cell_count,
        'anchor_wedge_verified': self.family_band.anchor_wedge_verified,
        'old_family_bridge_verified': False,
        'shock_entropy_closure_verified': False,
        'seed_flow_angle_jump_rad': self.seed.flow_angle_jump_rad,
      },
    )

  @property
  def boundary_sample_count(self) -> int:
    return len(self.boundary_states)

  def as_report(self) -> dict[str, object]:
    return {
      'status': self.status.value,
      'converged': self.converged,
      'physical_closure_verified': self.physical_closure_verified,
      'chain_promotion_blocked': self.chain_promotion_blocked,
      'anchor_wedge_verified': (
        None
        if self.family_band is None
        else self.family_band.anchor_wedge_verified
      ),
      'caustic_handoff_verified': self.caustic_handoff_verified,
      'anchor_edge_index': self.anchor_edge_index,
      'anchor_point_m': self.anchor_point_m,
      'anchor_state': (
        None
        if self.anchor_state is None
        else {
          'x_m': self.anchor_state.x_m,
          'y_m': self.anchor_state.y_m,
          'theta_rad': self.anchor_state.theta_rad,
          'mach': self.anchor_state.mach,
          'gamma': self.anchor_state.gamma,
        }
      ),
      'centerline_sample_count': len(self.centerline_states),
      'boundary_sample_count': self.boundary_sample_count,
      'boundary_points_m': [list(point) for point in self.boundary_points_m],
      'total_pressure_Pa': self.total_pressure_Pa,
      'ambient_pressure_Pa': self.ambient_pressure_Pa,
      'maximum_absolute_pressure_residual': self.maximum_absolute_pressure_residual,
      'maximum_absolute_tangent_residual': self.maximum_absolute_tangent_residual,
      'maximum_absolute_geometry_residual_m': self.maximum_absolute_geometry_residual_m,
      'minimum_forward_progress_m': self.minimum_forward_progress_m,
      'source_strip': (
        None
        if self.source_strip is None
        else {
          'status': self.source_strip.status.value,
          'converged': self.source_strip.converged,
          'node_count': self.source_strip.node_count,
          'cell_count': self.source_strip.cell_count,
          'topology_status': self.source_strip.topology.status.value,
          'topology_forms_closed_zone': self.source_strip.topology.forms_closed_zone,
          'topology_nonmanifold_edge_count': self.source_strip.topology.nonmanifold_edge_count,
          'message': self.source_strip.message,
        }
      ),
      'family_band': (
        None if self.family_band is None else self.family_band.as_report()
      ),
      'chain_termination_decision': (
        None
        if not self.caustic_handoff_verified
        else self.as_chain_termination_decision().as_report()
      ),
      'message': self.message,
    }


