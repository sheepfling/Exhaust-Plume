def _state_result_reportable(result: MocFreeBoundaryPointResult) -> bool:
  return (
    result.converged
    and result.state is not None
    and result.point_m is not None
  )


def _triangle_interpolation_weights(
  point: tuple[float, float],
  vertices: tuple[tuple[float, float], ...],
  *,
  tolerance_m: float,
) -> tuple[float, float, float] | None:
  """Return bounded barycentric weights for one triangular band cell."""

  first, second, third = vertices
  denominator = (
    (second[1] - third[1]) * (first[0] - third[0])
    + (third[0] - second[0]) * (first[1] - third[1])
  )
  if abs(denominator) <= tolerance_m:
    return None
  first_weight = (
    (second[1] - third[1]) * (point[0] - third[0])
    + (third[0] - second[0]) * (point[1] - third[1])
  ) / denominator
  second_weight = (
    (third[1] - first[1]) * (point[0] - third[0])
    + (first[0] - third[0]) * (point[1] - third[1])
  ) / denominator
  third_weight = 1.0 - first_weight - second_weight
  weight_tolerance = tolerance_m / max(
    1.0,
    abs(first[0]),
    abs(first[1]),
    abs(second[0]),
    abs(second[1]),
    abs(third[0]),
    abs(third[1]),
  )
  weights = (first_weight, second_weight, third_weight)
  if any(
    weight < -weight_tolerance or weight > 1.0 + weight_tolerance
    for weight in weights
  ):
    return None
  return tuple(max(0.0, min(1.0, weight)) for weight in weights)  # type: ignore[return-value]


def _assemble_open_family_band(
  centerline_states: tuple[CharacteristicState, ...],
  boundary_states: tuple[CharacteristicState, ...],
  *,
  total_pressure_Pa: float,
  position_tolerance_m: float,
  invariant_tolerance: float,
  seed_geometry_residual_m: float | None,
  anchor_point_m: tuple[float, float] | None,
  anchor_state: CharacteristicState | None,
) -> MocCausticFamilyBandResult:
  """Assemble the connected two-triangle band carried by the restart trace."""

  empty_topology = validate_moc_mesh(())
  input_edge = (
    ((centerline_states[0].x_m, centerline_states[0].y_m),
     (boundary_states[0].x_m, boundary_states[0].y_m))
    if centerline_states and boundary_states
    else ()
  )
  output_edge = (
    ((centerline_states[-1].x_m, centerline_states[-1].y_m),
     (boundary_states[-1].x_m, boundary_states[-1].y_m))
    if centerline_states and boundary_states
    else ()
  )
  anchor_progress = (
    min(point[0] - anchor_point_m[0] for point in input_edge)
    if anchor_point_m is not None and input_edge
    else None
  )

  def _failure(
    status: MocCausticFamilyBandStatus,
    message: str,
    *,
    cells: tuple[MocCharacteristicCell, ...] = (),
    topology: MocTopologyResult | None = None,
    geometry_residuals: tuple[float, ...] = (),
    invariant_residuals: tuple[float, ...] = (),
  ) -> MocCausticFamilyBandResult:
    geometry_values = tuple(geometry_residuals)
    if seed_geometry_residual_m is not None:
      geometry_values = (*geometry_values, abs(seed_geometry_residual_m))
    return MocCausticFamilyBandResult(
      status=status,
      centerline_states=centerline_states,
      boundary_states=boundary_states,
      total_pressure_Pa=total_pressure_Pa,
      cells=cells,
      topology=empty_topology if topology is None else topology,
      input_edge_points_m=input_edge,
      output_edge_points_m=output_edge,
      maximum_absolute_geometry_residual_m=max(geometry_values, default=None),
      maximum_absolute_invariant_residual=max(
        map(abs, invariant_residuals),
        default=None,
      ),
      message=message,
      anchor_point_m=anchor_point_m,
      anchor_state=anchor_state,
      anchor_to_input_min_forward_progress_m=anchor_progress,
    )

  if (anchor_point_m is None) != (anchor_state is None):
    return _failure(
      MocCausticFamilyBandStatus.INVALID_INPUT,
      'caustic family band anchor point and state must be supplied together',
    )
  if anchor_point_m is not None and anchor_state is not None:
    if (
      abs(anchor_state.x_m - anchor_point_m[0]) > position_tolerance_m
      or abs(anchor_state.y_m - anchor_point_m[1]) > position_tolerance_m
    ):
      return _failure(
        MocCausticFamilyBandStatus.INVALID_INPUT,
        'caustic family band anchor state does not match its anchor point',
      )
    if anchor_progress is None or anchor_progress <= position_tolerance_m:
      return _failure(
        MocCausticFamilyBandStatus.GEOMETRY_FAILURE,
        'caustic family band input edge is not downstream of its anchor',
      )

  if len(centerline_states) != len(boundary_states) or len(centerline_states) < 2:
    return _failure(
      MocCausticFamilyBandStatus.INVALID_INPUT,
      'caustic family band requires equal centerline and boundary arrays with at least two samples',
    )
  if any(
    not isinstance(state, CharacteristicState)
    for state in (*centerline_states, *boundary_states)
  ):
    return _failure(
      MocCausticFamilyBandStatus.INVALID_INPUT,
      'caustic family band states must be CharacteristicState values',
    )
  gamma = centerline_states[0].gamma
  if any(
    abs(state.gamma - gamma) > invariant_tolerance
    for state in (*centerline_states, *boundary_states)
  ):
    return _failure(
      MocCausticFamilyBandStatus.INVALID_INPUT,
      'caustic family band states must use one common gamma',
    )
  if any(abs(state.y_m) > position_tolerance_m for state in centerline_states):
    return _failure(
      MocCausticFamilyBandStatus.INVALID_INPUT,
      'caustic family band centerline states must lie on y=0',
    )

  geometry_residuals: list[float] = []
  invariant_residuals: list[float] = []
  cells: list[MocCharacteristicCell] = []
  if anchor_point_m is not None and anchor_state is not None:
    anchor_axis_result = centerline_characteristic_point(
      anchor_state,
      CharacteristicFamily.MINUS,
      position_tolerance_m=position_tolerance_m,
      invariant_tolerance=invariant_tolerance,
    )
    if (
      not anchor_axis_result.converged
      or anchor_axis_result.point_m is None
      or anchor_axis_result.state is None
    ):
      return _failure(
        MocCausticFamilyBandStatus.GEOMETRY_FAILURE,
        f'caustic anchor centerline trace failed: {anchor_axis_result.message}',
        geometry_residuals=tuple(geometry_residuals),
        invariant_residuals=tuple(invariant_residuals),
      )
    if anchor_axis_result.geometry_residual is not None:
      geometry_residuals.append(abs(anchor_axis_result.geometry_residual))
    anchor_axis_residual = sqrt(
      (anchor_axis_result.point_m[0] - centerline_states[0].x_m) ** 2
      + (anchor_axis_result.point_m[1] - centerline_states[0].y_m) ** 2
    )
    if anchor_axis_residual > position_tolerance_m:
      geometry_residuals.append(anchor_axis_residual)
      return _failure(
        MocCausticFamilyBandStatus.GEOMETRY_FAILURE,
        'caustic anchor centerline trace disagrees with the first restart state',
        geometry_residuals=tuple(geometry_residuals),
        invariant_residuals=tuple(invariant_residuals),
      )
    if centerline_states[0].x_m <= anchor_point_m[0] + position_tolerance_m:
      return _failure(
        MocCausticFamilyBandStatus.GEOMETRY_FAILURE,
        'caustic anchor centerline trace is not downstream',
        geometry_residuals=tuple(geometry_residuals),
        invariant_residuals=tuple(invariant_residuals),
      )
    anchor_compatibility_residual = (
      boundary_states[0].k_plus - centerline_states[0].k_plus
    )
    invariant_residuals.append(anchor_compatibility_residual)
    if abs(anchor_compatibility_residual) > invariant_tolerance:
      return _failure(
        MocCausticFamilyBandStatus.GEOMETRY_FAILURE,
        'caustic anchor ambient boundary does not preserve the first C+ invariant',
        geometry_residuals=tuple(geometry_residuals),
        invariant_residuals=tuple(invariant_residuals),
      )

  for index in range(1, len(centerline_states)):
    previous_boundary = boundary_states[index - 1]
    axis_state = centerline_states[index]
    boundary_state = boundary_states[index]
    axis_result = centerline_characteristic_point(
      previous_boundary,
      CharacteristicFamily.MINUS,
      position_tolerance_m=position_tolerance_m,
      invariant_tolerance=invariant_tolerance,
    )
    if (
      not axis_result.converged
      or axis_result.state is None
      or axis_result.point_m is None
    ):
      return _failure(
        MocCausticFamilyBandStatus.GEOMETRY_FAILURE,
        f'centerline trace failed at band step {index}: {axis_result.message}',
        cells=tuple(cells),
        geometry_residuals=tuple(geometry_residuals),
        invariant_residuals=tuple(invariant_residuals),
      )
    if axis_result.geometry_residual is not None:
      geometry_residuals.append(abs(axis_result.geometry_residual))
    point_residual = sqrt(
      (axis_result.point_m[0] - axis_state.x_m) ** 2
      + (axis_result.point_m[1] - axis_state.y_m) ** 2
    )
    if point_residual > position_tolerance_m:
      geometry_residuals.append(point_residual)
      return _failure(
        MocCausticFamilyBandStatus.GEOMETRY_FAILURE,
        f'centerline trace disagrees with restart state at band step {index}',
        cells=tuple(cells),
        geometry_residuals=tuple(geometry_residuals),
        invariant_residuals=tuple(invariant_residuals),
      )
    if axis_state.x_m <= centerline_states[index - 1].x_m + position_tolerance_m:
      return _failure(
        MocCausticFamilyBandStatus.GEOMETRY_FAILURE,
        f'centerline trace is not downstream at band step {index}',
        cells=tuple(cells),
        geometry_residuals=tuple(geometry_residuals),
        invariant_residuals=tuple(invariant_residuals),
      )
    if boundary_state.x_m <= previous_boundary.x_m + position_tolerance_m:
      return _failure(
        MocCausticFamilyBandStatus.GEOMETRY_FAILURE,
        f'ambient boundary is not downstream at band step {index}',
        cells=tuple(cells),
        geometry_residuals=tuple(geometry_residuals),
        invariant_residuals=tuple(invariant_residuals),
      )
    compatibility_residual = boundary_state.k_plus - axis_state.k_plus
    invariant_residuals.append(compatibility_residual)
    if abs(compatibility_residual) > invariant_tolerance:
      return _failure(
        MocCausticFamilyBandStatus.GEOMETRY_FAILURE,
        f'ambient C+ compatibility failed at band step {index}',
        cells=tuple(cells),
        geometry_residuals=tuple(geometry_residuals),
        invariant_residuals=tuple(invariant_residuals),
      )
    axis_previous_point = (
      centerline_states[index - 1].x_m,
      centerline_states[index - 1].y_m,
    )
    previous_boundary_point = (previous_boundary.x_m, previous_boundary.y_m)
    axis_point = (axis_state.x_m, axis_state.y_m)
    boundary_point = (boundary_state.x_m, boundary_state.y_m)
    try:
      cells.append(
        MocCharacteristicCell(
          cell_index=len(cells),
          cell_kind='caustic-restart-centerline-band',
          vertices_xr_m=(axis_previous_point, previous_boundary_point, axis_point),
          centerline_indices=(index - 1, index),
          boundary_indices=(index - 1,),
        )
      )
      cells.append(
        MocCharacteristicCell(
          cell_index=len(cells),
          cell_kind='caustic-restart-ambient-band',
          vertices_xr_m=(axis_point, previous_boundary_point, boundary_point),
          centerline_indices=(index,),
          boundary_indices=(index - 1, index),
        )
      )
    except (TypeError, ValueError) as error:
      return _failure(
        MocCausticFamilyBandStatus.GEOMETRY_FAILURE,
        f'caustic family band cell failed at step {index}: {error}',
        cells=tuple(cells),
        geometry_residuals=tuple(geometry_residuals),
        invariant_residuals=tuple(invariant_residuals),
      )

  if anchor_point_m is not None and anchor_state is not None:
    try:
      cells.append(
        MocCharacteristicCell(
          cell_index=len(cells),
          cell_kind='caustic-restart-anchor-wedge',
          vertices_xr_m=(
            anchor_point_m,
            (centerline_states[0].x_m, centerline_states[0].y_m),
            (boundary_states[0].x_m, boundary_states[0].y_m),
          ),
          centerline_indices=(0,),
          boundary_indices=(0,),
        )
      )
    except (TypeError, ValueError) as error:
      return _failure(
        MocCausticFamilyBandStatus.GEOMETRY_FAILURE,
        f'caustic family anchor wedge failed: {error}',
        cells=tuple(cells),
        geometry_residuals=tuple(geometry_residuals),
        invariant_residuals=tuple(invariant_residuals),
      )

  topology = validate_moc_mesh(tuple(cells))
  if not topology.connected or topology.nonmanifold_edge_count:
    return _failure(
      MocCausticFamilyBandStatus.TOPOLOGY_FAILURE,
      f'caustic family band topology failed: {topology.message}',
      cells=tuple(cells),
      topology=topology,
      geometry_residuals=tuple(geometry_residuals),
      invariant_residuals=tuple(invariant_residuals),
    )
  geometry_values = tuple(geometry_residuals)
  if seed_geometry_residual_m is not None:
    geometry_values = (*geometry_values, abs(seed_geometry_residual_m))
  return MocCausticFamilyBandResult(
    status=MocCausticFamilyBandStatus.CONVERGED_OPEN_BAND,
    centerline_states=centerline_states,
    boundary_states=boundary_states,
    total_pressure_Pa=total_pressure_Pa,
    cells=tuple(cells),
    topology=topology,
    input_edge_points_m=input_edge,
    output_edge_points_m=output_edge,
    maximum_absolute_geometry_residual_m=max(geometry_values, default=None),
    maximum_absolute_invariant_residual=max(
      map(abs, invariant_residuals),
      default=None,
    ),
    message=(
      'caustic restart produced a connected open anchor-wedge/two-triangle '
      'family band; '
      'shock fitting, downstream closure, and chain promotion remain blocked'
    ),
    anchor_point_m=anchor_point_m,
    anchor_state=anchor_state,
    anchor_to_input_min_forward_progress_m=anchor_progress,
  )


def restart_characteristic_family_from_caustic(
  seed: MocSourceStripCausticShockSeedResult,
  total_pressure_Pa: float,
  ambient_pressure_Pa: float,
  *,
  anchor_edge_index: int = 0,
  sample_count: int = 6,
  position_tolerance_m: float = 1.0e-10,
  invariant_tolerance: float = 1.0e-10,
  pressure_tolerance: float = 1.0e-10,
  maximum_iterations: int = 16,
) -> MocCausticFamilyRestartResult:
  """Restart an open reflected boundary from one side of a caustic.

  ``anchor_edge_index`` selects one already-solved one-sided C- edge.  The
  selected state is not averaged with the opposite edge and is not treated as
  a shock state.  A first C- reflection creates an axis state; each following
  C+ boundary point is solved against the previous ambient/tangent boundary.
  The optional triangular source-strip assembly is retained only as a local
  diagnostic because a caustic restart generally needs a new mesh family.
  """

  if not isinstance(seed, MocSourceStripCausticShockSeedResult):
    return _failure(
      MocCausticFamilyRestartStatus.INVALID_INPUT,
      seed=None,
      anchor_edge_index=None,
      message='seed must be a MocSourceStripCausticShockSeedResult',
    )
  try:
    total_pressure = float(total_pressure_Pa)
    ambient_pressure = float(ambient_pressure_Pa)
  except (TypeError, ValueError):
    return _failure(
      MocCausticFamilyRestartStatus.INVALID_INPUT,
      seed=seed,
      anchor_edge_index=anchor_edge_index,
      message='pressures must be finite numeric values',
    )
  if (
    not isfinite(total_pressure)
    or total_pressure <= 0.0
    or not isfinite(ambient_pressure)
    or ambient_pressure <= 0.0
    or total_pressure <= ambient_pressure
  ):
    return _failure(
      MocCausticFamilyRestartStatus.INVALID_INPUT,
      seed=seed,
      anchor_edge_index=anchor_edge_index,
      total_pressure_Pa=total_pressure,
      ambient_pressure_Pa=ambient_pressure,
      message='total pressure must exceed finite positive ambient pressure',
    )
  if (
    isinstance(anchor_edge_index, bool)
    or not isinstance(anchor_edge_index, int)
    or anchor_edge_index not in (0, 1)
  ):
    return _failure(
      MocCausticFamilyRestartStatus.INVALID_INPUT,
      seed=seed,
      anchor_edge_index=anchor_edge_index,
      total_pressure_Pa=total_pressure,
      ambient_pressure_Pa=ambient_pressure,
      message='anchor_edge_index must be 0 or 1',
    )
  if (
    isinstance(sample_count, bool)
    or not isinstance(sample_count, int)
    or sample_count < 3
  ):
    return _failure(
      MocCausticFamilyRestartStatus.INVALID_INPUT,
      seed=seed,
      anchor_edge_index=anchor_edge_index,
      total_pressure_Pa=total_pressure,
      ambient_pressure_Pa=ambient_pressure,
      message='sample_count must be an integer of at least three',
    )
  for name, value in (
    ('position_tolerance_m', position_tolerance_m),
    ('invariant_tolerance', invariant_tolerance),
    ('pressure_tolerance', pressure_tolerance),
  ):
    if not isfinite(float(value)) or value <= 0.0:
      raise ValueError(f'{name} must be finite and positive')
  if isinstance(maximum_iterations, bool) or maximum_iterations < 1:
    raise ValueError('maximum_iterations must be a positive integer')
  if not seed.converged or len(seed.edge_states) != 2:
    return _failure(
      MocCausticFamilyRestartStatus.SEED_FAILURE,
      seed=seed,
      anchor_edge_index=anchor_edge_index,
      total_pressure_Pa=total_pressure,
      ambient_pressure_Pa=ambient_pressure,
      message=f'caustic restart seed is not usable: {seed.message}',
    )
  anchor = seed.edge_states[anchor_edge_index]
  if anchor.state is None or anchor.point_m is None:
    return _failure(
      MocCausticFamilyRestartStatus.SEED_FAILURE,
      seed=seed,
      anchor_edge_index=anchor_edge_index,
      total_pressure_Pa=total_pressure,
      ambient_pressure_Pa=ambient_pressure,
      message='selected caustic edge does not carry a one-sided anchor state',
    )
  anchor_state = anchor.state
  centerline_states: list[CharacteristicState] = []
  boundary_states: list[CharacteristicState] = []
  boundary_points: list[tuple[float, float]] = []
  pressure_residuals: list[float] = []
  tangent_residuals: list[float] = []
  geometry_residuals: list[float] = []
  forward_progress: list[float] = []
  previous_boundary = anchor_state
  for step in range(sample_count):
    axis_result = centerline_characteristic_point(
      previous_boundary,
      CharacteristicFamily.MINUS,
      position_tolerance_m=position_tolerance_m,
      invariant_tolerance=invariant_tolerance,
    )
    if not axis_result.converged or axis_result.state is None:
      return _failure(
        MocCausticFamilyRestartStatus.CENTERLINE_FAILURE,
        seed=seed,
        anchor_edge_index=anchor_edge_index,
        anchor_point_m=anchor.point_m,
        anchor_state=anchor_state,
        centerline_states=tuple(centerline_states),
        boundary_states=tuple(boundary_states),
        boundary_points_m=tuple(boundary_points),
        total_pressure_Pa=total_pressure,
        ambient_pressure_Pa=ambient_pressure,
        maximum_absolute_pressure_residual=max(map(abs, pressure_residuals), default=None),
        maximum_absolute_tangent_residual=max(map(abs, tangent_residuals), default=None),
        maximum_absolute_geometry_residual_m=max(map(abs, geometry_residuals), default=None),
        minimum_forward_progress_m=min(forward_progress, default=None),
        message=f'caustic restart centerline reflection failed at step {step}: {axis_result.message}',
      )
    boundary_result = solve_ambient_pressure_free_boundary_point(
      axis_result.state,
      previous_boundary,
      CharacteristicFamily.PLUS,
      total_pressure_Pa=total_pressure,
      ambient_pressure_Pa=ambient_pressure,
      position_tolerance_m=position_tolerance_m,
      pressure_tolerance=pressure_tolerance,
      maximum_iterations=maximum_iterations,
    )
    if not _state_result_reportable(boundary_result):
      return _failure(
        MocCausticFamilyRestartStatus.AMBIENT_BOUNDARY_FAILURE,
        seed=seed,
        anchor_edge_index=anchor_edge_index,
        anchor_point_m=anchor.point_m,
        anchor_state=anchor_state,
        centerline_states=tuple(centerline_states),
        boundary_states=tuple(boundary_states),
        boundary_points_m=tuple(boundary_points),
        total_pressure_Pa=total_pressure,
        ambient_pressure_Pa=ambient_pressure,
        maximum_absolute_pressure_residual=max(map(abs, pressure_residuals), default=None),
        maximum_absolute_tangent_residual=max(map(abs, tangent_residuals), default=None),
        maximum_absolute_geometry_residual_m=max(map(abs, geometry_residuals), default=None),
        minimum_forward_progress_m=min(forward_progress, default=None),
        message=f'caustic restart ambient boundary failed at step {step}: {boundary_result.message}',
      )
    assert boundary_result.state is not None
    assert boundary_result.point_m is not None
    progress = boundary_result.point_m[0] - previous_boundary.x_m
    if progress <= position_tolerance_m:
      return _failure(
        MocCausticFamilyRestartStatus.AMBIENT_BOUNDARY_FAILURE,
        seed=seed,
        anchor_edge_index=anchor_edge_index,
        anchor_point_m=anchor.point_m,
        anchor_state=anchor_state,
        centerline_states=tuple(centerline_states),
        boundary_states=tuple(boundary_states),
        boundary_points_m=tuple(boundary_points),
        total_pressure_Pa=total_pressure,
        ambient_pressure_Pa=ambient_pressure,
        maximum_absolute_pressure_residual=max(map(abs, pressure_residuals), default=None),
        maximum_absolute_tangent_residual=max(map(abs, tangent_residuals), default=None),
        maximum_absolute_geometry_residual_m=max(map(abs, geometry_residuals), default=None),
        minimum_forward_progress_m=min(forward_progress, default=None),
        message='caustic restart ambient boundary did not make downstream progress',
      )
    centerline_states.append(axis_result.state)
    boundary_states.append(boundary_result.state)
    boundary_points.append(boundary_result.point_m)
    pressure_residuals.append(boundary_result.pressure_residual or 0.0)
    tangent_residuals.append(boundary_result.tangent_residual or 0.0)
    geometry_residuals.append(boundary_result.geometry_residual or 0.0)
    forward_progress.append(progress)
    previous_boundary = boundary_result.state

  source_strip = assemble_source_characteristic_strip(
    tuple(centerline_states),
    tuple(boundary_states),
    total_pressure,
    position_tolerance_m=position_tolerance_m,
    invariant_tolerance=invariant_tolerance,
  )
  family_band = _assemble_open_family_band(
    tuple(centerline_states),
    tuple(boundary_states),
    total_pressure_Pa=total_pressure,
    position_tolerance_m=position_tolerance_m,
    invariant_tolerance=invariant_tolerance,
    seed_geometry_residual_m=anchor.geometry_residual_m,
    anchor_point_m=anchor.point_m,
    anchor_state=anchor_state,
  )
  return MocCausticFamilyRestartResult(
    status=(
      MocCausticFamilyRestartStatus.CONVERGED_OPEN_BOUNDARY
      if family_band.converged
      else MocCausticFamilyRestartStatus.BAND_FAILURE
    ),
    seed=seed,
    anchor_edge_index=anchor_edge_index,
    anchor_point_m=anchor.point_m,
    anchor_state=anchor_state,
    centerline_states=tuple(centerline_states),
    boundary_states=tuple(boundary_states),
    boundary_points_m=tuple(boundary_points),
    total_pressure_Pa=total_pressure,
    ambient_pressure_Pa=ambient_pressure,
    maximum_absolute_pressure_residual=max(map(abs, pressure_residuals), default=None),
    maximum_absolute_tangent_residual=max(map(abs, tangent_residuals), default=None),
    maximum_absolute_geometry_residual_m=max(map(abs, geometry_residuals), default=None),
    minimum_forward_progress_m=min(forward_progress, default=None),
    source_strip=source_strip,
    family_band=family_band,
    message=(
      'one-sided caustic family restart converged as an open '
      'centerline/ambient boundary; triangular interior remesh and shock '
      'closure remain separate gates'
      if family_band.converged
      else f'caustic family band assembly failed: {family_band.message}'
    ),
  )
