def _wrapped_angle_difference(first: float, second: float) -> float:
  difference = float(first) - float(second)
  while difference > pi:
    difference -= 2.0 * pi
  while difference < -pi:
    difference += 2.0 * pi
  return difference


def fit_attached_shock_boundary(
    upstream_states: Sequence[CharacteristicState],
    upstream_pressure_Pa: Sequence[float],
    shock_points_m: Sequence[tuple[float, float]],
    downstream_flow_angles_rad: Sequence[float],
    *,
    branch: ShockBranch = ShockBranch.WEAK,
    position_tolerance_m: float = 1.0e-10,
    shock_angle_tolerance_rad: float = 1.0e-8,
) -> MocShockBoundaryFitResult:
  """Fit downstream attached states to an explicitly sampled shock curve.

  The geometry is supplied, never invented: each upstream state must be
  located on its corresponding shock sample, and the local tangent must agree
  with the attached oblique-shock angle returned for the requested downstream
  turn.  This is the deterministic boundary contract needed by the post-shock
  field assembler; it is not an automatic free-boundary shock finder.
  """

  samples = tuple(upstream_states)
  pressures = tuple(upstream_pressure_Pa)
  points = tuple(shock_points_m)
  target_angles = tuple(downstream_flow_angles_rad)
  if len(samples) < 2:
    return _shock_fit_failure(
      MocShockBoundaryFitStatus.INVALID_INPUT,
      message='shock boundary fit requires at least two samples',
    )
  if not (len(samples) == len(pressures) == len(points) == len(target_angles)):
    return _shock_fit_failure(
      MocShockBoundaryFitStatus.INVALID_INPUT,
      message='upstream states, pressures, points, and target angles must have equal lengths',
    )
  if not isinstance(branch, ShockBranch):
    return _shock_fit_failure(
      MocShockBoundaryFitStatus.INVALID_INPUT,
      message='branch must be a ShockBranch',
    )
  for name, value in (
    ('position_tolerance_m', position_tolerance_m),
    ('shock_angle_tolerance_rad', shock_angle_tolerance_rad),
  ):
    if not isfinite(float(value)) or value <= 0.0:
      raise ValueError(f'{name} must be finite and positive')
  if not all(isinstance(state, CharacteristicState) for state in samples):
    return _shock_fit_failure(
      MocShockBoundaryFitStatus.INVALID_INPUT,
      message='upstream_states must contain CharacteristicState values',
    )
  gamma = samples[0].gamma
  previous_point: tuple[float, float] | None = None
  for index, (state, pressure, point, target_angle) in enumerate(
      zip(samples, pressures, points, target_angles, strict=True)
  ):
    if abs(state.gamma - gamma) > shock_angle_tolerance_rad:
      return _shock_fit_failure(
        MocShockBoundaryFitStatus.INVALID_INPUT,
        message=f'shock sample {index} uses a different gamma',
      )
    if len(point) != 2 or not all(isfinite(float(value)) for value in point):
      return _shock_fit_failure(
        MocShockBoundaryFitStatus.INVALID_INPUT,
        message=f'shock sample {index} has a non-finite point',
      )
    if abs(state.x_m - point[0]) > position_tolerance_m or abs(state.y_m - point[1]) > position_tolerance_m:
      return _shock_fit_failure(
        MocShockBoundaryFitStatus.INVALID_INPUT,
        message=f'upstream state {index} does not lie on its shock sample',
      )
    if not isfinite(float(pressure)) or pressure <= 0.0:
      return _shock_fit_failure(
        MocShockBoundaryFitStatus.INVALID_INPUT,
        message=f'upstream pressure {index} must be finite and positive',
      )
    if not isfinite(float(target_angle)):
      return _shock_fit_failure(
        MocShockBoundaryFitStatus.INVALID_INPUT,
        message=f'downstream flow angle {index} must be finite',
      )
    if previous_point is not None:
      dx = float(point[0]) - previous_point[0]
      dy = float(point[1]) - previous_point[1]
      if dx <= position_tolerance_m or dy > position_tolerance_m:
        return _shock_fit_failure(
          MocShockBoundaryFitStatus.INVALID_INPUT,
          message=(
            'shock samples must be strictly downstream in x and nonincreasing '
            'in y'
          ),
        )
    previous_point = (float(point[0]), float(point[1]))
  ####

  fitted: list[MocPostShockBoundaryState] = []
  angle_residuals: list[float] = []
  fitted_upstream_total_pressures: list[float] = []
  for index, (state, pressure, point, target_angle) in enumerate(
      zip(samples, pressures, points, target_angles, strict=True)
  ):
    target_turn = float(target_angle) - state.theta_rad
    if target_turn <= 0.0:
      return _shock_fit_failure(
        MocShockBoundaryFitStatus.OUTSIDE_DOMAIN,
        boundary_states=tuple(fitted),
        residuals=tuple(angle_residuals),
        message=f'shock sample {index} does not require a positive compression turn',
      )
    compression = solve_attached_compression_to_turn(
      upstream_mach=state.mach,
      gamma=state.gamma,
      upstream_pressure_Pa=float(pressure),
      target_turn_rad=target_turn,
      branch=branch,
    )
    if (
      not compression.converged
      or compression.beta_rad is None
      or compression.downstream_mach is None
      or compression.upstream_total_pressure_Pa is None
      or compression.downstream_total_pressure_Pa is None
    ):
      status = (
        MocShockBoundaryFitStatus.INVARIANT_FAILURE
        if compression.status is MocPrimitiveStatus.INVARIANT_FAILURE
        else MocShockBoundaryFitStatus.OUTSIDE_DOMAIN
      )
      return _shock_fit_failure(
        status,
        boundary_states=tuple(fitted),
        residuals=tuple(angle_residuals),
        message=f'shock sample {index} failed attached compression: {compression.message}',
      )
    if index == 0:
      tangent_dx = points[1][0] - points[0][0]
      tangent_dy = points[1][1] - points[0][1]
    elif index == len(points) - 1:
      tangent_dx = points[-1][0] - points[-2][0]
      tangent_dy = points[-1][1] - points[-2][1]
    else:
      tangent_dx = points[index + 1][0] - points[index - 1][0]
      tangent_dy = points[index + 1][1] - points[index - 1][1]
    tangent_angle = atan2(tangent_dy, tangent_dx)
    shock_angle = state.theta_rad - compression.beta_rad
    angle_residual = _wrapped_angle_difference(tangent_angle, shock_angle)
    angle_residuals.append(angle_residual)
    if abs(angle_residual) > shock_angle_tolerance_rad:
      return _shock_fit_failure(
        MocShockBoundaryFitStatus.GEOMETRY_FAILURE,
        boundary_states=tuple(fitted),
        residuals=tuple(angle_residuals),
        message=(
          f'shock sample {index} tangent disagrees with attached shock angle '
          f'by {angle_residual}'
        ),
      )
    fitted.append(
      MocPostShockBoundaryState(
        point_m=(float(point[0]), float(point[1])),
        state=CharacteristicState(
          x_m=float(point[0]),
          y_m=float(point[1]),
          theta_rad=float(target_angle),
          mach=float(compression.downstream_mach),
          gamma=state.gamma,
        ),
        upstream_total_pressure_Pa=float(compression.upstream_total_pressure_Pa),
        downstream_total_pressure_Pa=float(compression.downstream_total_pressure_Pa),
      )
    )
    fitted_upstream_total_pressures.append(
      float(compression.upstream_total_pressure_Pa)
    )
  ####

  return MocShockBoundaryFitResult(
    status=MocShockBoundaryFitStatus.CONVERGED_FITTED,
    boundary_states=tuple(fitted),
    shock_angle_residuals_rad=tuple(angle_residuals),
    maximum_shock_angle_residual_rad=max(
      (abs(value) for value in angle_residuals),
      default=None,
    ),
    upstream_states=samples,
    upstream_total_pressure_Pa=tuple(fitted_upstream_total_pressures),
  )
####


@dataclass(frozen=True, slots=True)
class _PostShockFrontSample:
  state: CharacteristicState
  total_pressure_Pa: float


def _post_shock_field_failure(
  status: MocPostShockFieldStatus,
  *,
  characteristic_layer_count: int = 0,
  nodes: tuple[MocCharacteristicNode, ...] = (),
  cells: tuple[MocCharacteristicCell, ...] = (),
  topology: MocTopologyResult | None = None,
  shock_boundary_points: tuple[tuple[float, float], ...] = (),
  centerline_boundary_points: tuple[tuple[float, float], ...] = (),
  upstream_boundary_states: tuple[CharacteristicState, ...] = (),
  upstream_boundary_total_pressure_Pa: tuple[float, ...] = (),
  continuation_boundary_states: tuple[CharacteristicState, ...] = (),
  continuation_boundary_total_pressure_Pa: tuple[float, ...] = (),
  incoming_handoff_states: tuple[CharacteristicState, ...] = (),
  incoming_handoff_total_pressure_Pa: tuple[float, ...] = (),
  terminal_centerline_state: CharacteristicState | None = None,
  maximum_geometry_residual_m: float | None = None,
  maximum_absolute_invariant_residual: float | None = None,
  minimum_forward_margin_m: float | None = None,
  pressure_ranges: tuple[tuple[float, float], tuple[float, float]] | None = None,
  pressure_ratios: tuple[float, ...] = (),
  message: str,
) -> MocPostShockCharacteristicFieldResult:
  return MocPostShockCharacteristicFieldResult(
    status=status,
    characteristic_layer_count=characteristic_layer_count,
    nodes=nodes,
    cells=cells,
    topology=validate_moc_mesh(()) if topology is None else topology,
    shock_boundary_points_m=shock_boundary_points,
    centerline_boundary_points_m=centerline_boundary_points,
    upstream_boundary_states=upstream_boundary_states,
    upstream_boundary_total_pressure_Pa=upstream_boundary_total_pressure_Pa,
    continuation_boundary_states=continuation_boundary_states,
    continuation_boundary_total_pressure_Pa=continuation_boundary_total_pressure_Pa,
    incoming_handoff_states=incoming_handoff_states,
    incoming_handoff_total_pressure_Pa=incoming_handoff_total_pressure_Pa,
    terminal_centerline_state=terminal_centerline_state,
    maximum_geometry_residual_m=maximum_geometry_residual_m,
    maximum_absolute_invariant_residual=maximum_absolute_invariant_residual,
    minimum_forward_margin_m=minimum_forward_margin_m,
    upstream_total_pressure_range_Pa=(pressure_ranges[0] if pressure_ranges is not None else None),
    downstream_total_pressure_range_Pa=(pressure_ranges[1] if pressure_ranges is not None else None),
    minimum_post_shock_total_pressure_ratio=min(pressure_ratios, default=None),
    maximum_post_shock_total_pressure_ratio=max(pressure_ratios, default=None),
    physical_closure_status='not_closed',
    shock_closure_status='not_assembled',
    message=message,
  )


def assemble_post_shock_characteristic_field(
  shock_fit: MocShockBoundaryFitResult,
  *,
  incoming_handoff: Sequence[MocChainBoundarySample] | None = None,
  position_tolerance_m: float = 1.0e-10,
  invariant_tolerance: float = 1.0e-10,
  shock_angle_tolerance_rad: float = 1.0e-8,
) -> MocPostShockCharacteristicFieldResult:
  """Generate a closed shock-seeded downstream planar characteristic field.

  The ordered fitted shock samples are the initial boundary.  Each new front
  is formed from ``C+`` of the later front state and ``C-`` of the earlier
  front state, so the front count decreases by one per characteristic layer.
  The terminal state is continued to the symmetry line and a characteristic
  closure fan is added at the terminal side.  A failed forward intersection,
  invariant check, pressure-loss check, or mesh edge check is returned as a
  structured failure; no geometric fallback is inserted.

  ``incoming_handoff`` is optional for the first cell.  For a continued cell,
  the caller supplies the prior cell's typed carried boundary and the returned
  field records that boundary as consumed.  It is not assumed to be an axial
  section and is not reused as the next shock geometry; a local continuation
  solver must propagate it to its own shock boundary first.
  """

  if not isinstance(shock_fit, MocShockBoundaryFitResult):
    return _post_shock_field_failure(
      MocPostShockFieldStatus.INVALID_INPUT,
      message='shock_fit must be a MocShockBoundaryFitResult',
    )
  for name, value in (
    ('position_tolerance_m', position_tolerance_m),
    ('invariant_tolerance', invariant_tolerance),
    ('shock_angle_tolerance_rad', shock_angle_tolerance_rad),
  ):
    if not isfinite(float(value)) or value <= 0.0:
      raise ValueError(f'{name} must be finite and positive')
  if not shock_fit.converged:
    return _post_shock_field_failure(
      MocPostShockFieldStatus.SHOCK_FIT_REQUIRED,
      message=f'characteristic field requires a converged shock fit: {shock_fit.message}',
    )
  incoming_samples = () if incoming_handoff is None else tuple(incoming_handoff)
  if any(not isinstance(sample, MocChainBoundarySample) for sample in incoming_samples):
    return _post_shock_field_failure(
      MocPostShockFieldStatus.INVALID_INPUT,
      message='incoming_handoff must contain MocChainBoundarySample values',
    )
  if incoming_handoff is not None and len(incoming_samples) < 3:
    return _post_shock_field_failure(
      MocPostShockFieldStatus.INVALID_INPUT,
      message='incoming_handoff requires at least three state samples',
    )
  incoming_states = tuple(sample.state for sample in incoming_samples)
  incoming_pressures = tuple(sample.total_pressure_Pa for sample in incoming_samples)
  samples = tuple(shock_fit.boundary_states)
  if len(samples) < 3:
    return _post_shock_field_failure(
      MocPostShockFieldStatus.INVALID_INPUT,
      message='shock-seeded characteristic field requires at least three shock samples',
    )
  upstream_boundary_states = tuple(shock_fit.upstream_states)
  upstream_boundary_total_pressures = tuple(shock_fit.upstream_total_pressure_Pa)
  if bool(upstream_boundary_states) != bool(upstream_boundary_total_pressures):
    return _post_shock_field_failure(
      MocPostShockFieldStatus.INVALID_INPUT,
      message=(
        'shock-fit state carry must provide both upstream states and upstream '
        'total-pressure samples'
      ),
    )
  if upstream_boundary_states and (
    len(upstream_boundary_states) != len(samples)
    or len(upstream_boundary_total_pressures) != len(samples)
  ):
    return _post_shock_field_failure(
      MocPostShockFieldStatus.INVALID_INPUT,
      message='shock-fit upstream state carry must match its downstream sample count',
    )
  shock_points = tuple(sample.point_m for sample in samples)
  upstream_values = tuple(sample.upstream_total_pressure_Pa for sample in samples)
  downstream_values = tuple(sample.downstream_total_pressure_Pa for sample in samples)
  pressure_ranges = (
    (min(upstream_values), max(upstream_values)),
    (min(downstream_values), max(downstream_values)),
  )
  pressure_ratios = tuple(
    downstream / upstream
    for upstream, downstream in zip(upstream_values, downstream_values, strict=True)
  )
  if upstream_boundary_total_pressures and any(
    abs(carried - expected) > position_tolerance_m * max(1.0, abs(expected))
    for carried, expected in zip(
      upstream_boundary_total_pressures,
      upstream_values,
      strict=True,
    )
  ):
    return _post_shock_field_failure(
      MocPostShockFieldStatus.PRESSURE_FAILURE,
      shock_boundary_points=shock_points,
      upstream_boundary_states=upstream_boundary_states,
      upstream_boundary_total_pressure_Pa=upstream_boundary_total_pressures,
      pressure_ranges=pressure_ranges,
      pressure_ratios=pressure_ratios,
      message='shock-fit upstream total-pressure carry disagrees with its shock samples',
    )
  if any(ratio <= 0.0 or ratio >= 1.0 for ratio in pressure_ratios):
    return _post_shock_field_failure(
      MocPostShockFieldStatus.PRESSURE_FAILURE,
      shock_boundary_points=shock_points,
      pressure_ranges=pressure_ranges,
      pressure_ratios=pressure_ratios,
      message='shock-seeded characteristic field requires strict positive total-pressure loss at every shock sample',
    )
  if (
    shock_fit.maximum_shock_angle_residual_rad is None
    or shock_fit.maximum_shock_angle_residual_rad > shock_angle_tolerance_rad
  ):
    return _post_shock_field_failure(
      MocPostShockFieldStatus.GEOMETRY_FAILURE,
      shock_boundary_points=shock_points,
      pressure_ranges=pressure_ranges,
      pressure_ratios=pressure_ratios,
      message='shock-fit tangent residual exceeds the characteristic-field tolerance',
    )
  if any(
    abs(sample.state.x_m - sample.point_m[0]) > position_tolerance_m
    or abs(sample.state.y_m - sample.point_m[1]) > position_tolerance_m
    for sample in samples
  ):
    return _post_shock_field_failure(
      MocPostShockFieldStatus.INVALID_INPUT,
      shock_boundary_points=shock_points,
      pressure_ranges=pressure_ranges,
      pressure_ratios=pressure_ratios,
      message='shock boundary state coordinates must match their fitted points',
    )
  if upstream_boundary_states and any(
    abs(state.x_m - point[0]) > position_tolerance_m
    or abs(state.y_m - point[1]) > position_tolerance_m
    for state, point in zip(upstream_boundary_states, shock_points, strict=True)
  ):
    return _post_shock_field_failure(
      MocPostShockFieldStatus.INVALID_INPUT,
      shock_boundary_points=shock_points,
      upstream_boundary_states=upstream_boundary_states,
      upstream_boundary_total_pressure_Pa=upstream_boundary_total_pressures,
      incoming_handoff_states=incoming_states,
      incoming_handoff_total_pressure_Pa=incoming_pressures,
      pressure_ranges=pressure_ranges,
      pressure_ratios=pressure_ratios,
      message='shock-fit upstream states must lie on the fitted shock samples',
    )
  if abs(shock_points[-1][1]) > position_tolerance_m:
    return _post_shock_field_failure(
      MocPostShockFieldStatus.GEOMETRY_FAILURE,
      shock_boundary_points=shock_points,
      pressure_ranges=pressure_ranges,
      pressure_ratios=pressure_ratios,
      message='the fitted shock boundary must terminate on the symmetry line',
    )
  if abs(samples[-1].state.theta_rad) > invariant_tolerance:
    return _post_shock_field_failure(
      MocPostShockFieldStatus.INVARIANT_FAILURE,
      shock_boundary_points=shock_points,
      pressure_ranges=pressure_ranges,
      pressure_ratios=pressure_ratios,
      message='the terminal fitted shock state must satisfy centerline theta = 0',
    )
  ####

  fronts: list[tuple[_PostShockFrontSample, ...]] = [
    tuple(
      _PostShockFrontSample(
        state=sample.state,
        total_pressure_Pa=sample.downstream_total_pressure_Pa,
      )
      for sample in samples
    )
  ]
  nodes_list: list[MocCharacteristicNode] = []
  cells_list: list[MocCharacteristicCell] = []
  forward_margins: list[float] = []
  layer_index = 0
  while len(fronts[-1]) > 1:
    front = fronts[-1]
    next_front: list[_PostShockFrontSample] = []
    for index in range(len(front) - 1):
      plus_source = front[index + 1]
      minus_source = front[index]
      point_result = interior_characteristic_point(
        plus_source.state,
        minus_source.state,
        position_tolerance_m=position_tolerance_m,
        invariant_tolerance=invariant_tolerance,
      )
      if not point_result.converged or point_result.state is None or point_result.point_m is None:
        status = (
          MocPostShockFieldStatus.INVARIANT_FAILURE
          if point_result.status is MocPrimitiveStatus.INVARIANT_FAILURE
          else MocPostShockFieldStatus.GEOMETRY_FAILURE
        )
        return _post_shock_field_failure(
          status,
          characteristic_layer_count=layer_index,
          nodes=tuple(nodes_list),
          cells=tuple(cells_list),
          shock_boundary_points=shock_points,
          pressure_ranges=pressure_ranges,
          pressure_ratios=pressure_ratios,
          maximum_geometry_residual_m=max(
            (abs(node.point_result.geometry_residual) for node in nodes_list if node.point_result.geometry_residual is not None),
            default=None,
          ),
          message=(
            f'post-shock characteristic layer {layer_index} intersection '
            f'{index} failed: {point_result.message}'
          ),
        )
      point = point_result.point_m
      if point[1] < -position_tolerance_m:
        return _post_shock_field_failure(
          MocPostShockFieldStatus.GEOMETRY_FAILURE,
          characteristic_layer_count=layer_index,
          nodes=tuple(nodes_list),
          cells=tuple(cells_list),
          shock_boundary_points=shock_points,
          pressure_ranges=pressure_ranges,
          pressure_ratios=pressure_ratios,
          message=(
            f'post-shock characteristic layer {layer_index} intersection '
            f'{index} crossed below the symmetry line'
          ),
        )
      forward_margin = point[0] - max(
        plus_source.state.x_m,
        minus_source.state.x_m,
      )
      if forward_margin <= position_tolerance_m:
        return _post_shock_field_failure(
          MocPostShockFieldStatus.GEOMETRY_FAILURE,
          characteristic_layer_count=layer_index,
          nodes=tuple(nodes_list),
          cells=tuple(cells_list),
          shock_boundary_points=shock_points,
          pressure_ranges=pressure_ranges,
          pressure_ratios=pressure_ratios,
          message=(
            f'post-shock characteristic layer {layer_index} intersection '
            f'{index} has no forward margin'
          ),
        )
      forward_margins.append(forward_margin)
      next_sample = _PostShockFrontSample(
        state=point_result.state,
        total_pressure_Pa=minus_source.total_pressure_Pa,
      )
      next_front.append(next_sample)
      nodes_list.append(
        MocCharacteristicNode(
          centerline_index=layer_index + 1,
          boundary_index=index,
          point_m=(float(point[0]), float(point[1])),
          state=point_result.state,
          point_result=point_result,
          total_pressure_Pa=minus_source.total_pressure_Pa,
        )
      )
    ####
    try:
      for index in range(len(next_front) - 1):
        cells_list.append(
          MocCharacteristicCell(
            cell_index=len(cells_list),
            cell_kind=f'post-shock-characteristic-layer-{layer_index}',
            vertices_xr_m=(
              (front[index].state.x_m, front[index].state.y_m),
              (front[index + 1].state.x_m, front[index + 1].state.y_m),
              (next_front[index + 1].state.x_m, next_front[index + 1].state.y_m),
              (next_front[index].state.x_m, next_front[index].state.y_m),
            ),
            centerline_indices=(layer_index,),
            boundary_indices=(index, index + 1),
          )
        )
      cells_list.append(
        MocCharacteristicCell(
          cell_index=len(cells_list),
          cell_kind=f'post-shock-characteristic-terminal-{layer_index}',
          vertices_xr_m=(
            (front[-2].state.x_m, front[-2].state.y_m),
            (front[-1].state.x_m, front[-1].state.y_m),
            (next_front[-1].state.x_m, next_front[-1].state.y_m),
          ),
          centerline_indices=(layer_index,),
          boundary_indices=(len(next_front) - 1, len(next_front)),
        )
      )
    except ValueError as error:
      return _post_shock_field_failure(
        MocPostShockFieldStatus.GEOMETRY_FAILURE,
        characteristic_layer_count=layer_index,
        nodes=tuple(nodes_list),
        cells=tuple(cells_list),
        shock_boundary_points=shock_points,
        pressure_ranges=pressure_ranges,
        pressure_ratios=pressure_ratios,
        message=f'post-shock characteristic layer cell geometry failed: {error}',
      )
    fronts.append(tuple(next_front))
    layer_index += 1
  ####

  terminal_front = fronts[-1]
  if not terminal_front:
    return _post_shock_field_failure(
      MocPostShockFieldStatus.GEOMETRY_FAILURE,
      characteristic_layer_count=layer_index,
      nodes=tuple(nodes_list),
      cells=tuple(cells_list),
      shock_boundary_points=shock_points,
      pressure_ranges=pressure_ranges,
      pressure_ratios=pressure_ratios,
      message='post-shock characteristic march produced an empty terminal front',
    )
  terminal = terminal_front[0]
  centerline_result = centerline_characteristic_point(
    terminal.state,
    CharacteristicFamily.MINUS,
    position_tolerance_m=position_tolerance_m,
    invariant_tolerance=invariant_tolerance,
  )
  if not centerline_result.converged or centerline_result.state is None or centerline_result.point_m is None:
    status = (
      MocPostShockFieldStatus.INVARIANT_FAILURE
      if centerline_result.status is MocPrimitiveStatus.INVARIANT_FAILURE
      else MocPostShockFieldStatus.CENTERLINE_FAILURE
    )
    return _post_shock_field_failure(
      status,
      characteristic_layer_count=layer_index,
      nodes=tuple(nodes_list),
      cells=tuple(cells_list),
      shock_boundary_points=shock_points,
      pressure_ranges=pressure_ranges,
      pressure_ratios=pressure_ratios,
      message=f'terminal post-shock characteristic did not reach the centerline: {centerline_result.message}',
    )
  centerline_point = centerline_result.point_m
  if abs(centerline_point[1]) > position_tolerance_m:
    return _post_shock_field_failure(
      MocPostShockFieldStatus.CENTERLINE_FAILURE,
      characteristic_layer_count=layer_index,
      nodes=tuple(nodes_list),
      cells=tuple(cells_list),
      shock_boundary_points=shock_points,
      pressure_ranges=pressure_ranges,
      pressure_ratios=pressure_ratios,
      message='terminal post-shock characteristic did not reproduce y=0',
    )
  terminal_forward_margin = centerline_point[0] - terminal.state.x_m
  if terminal_forward_margin <= position_tolerance_m:
    return _post_shock_field_failure(
      MocPostShockFieldStatus.CENTERLINE_FAILURE,
      characteristic_layer_count=layer_index,
      nodes=tuple(nodes_list),
      cells=tuple(cells_list),
      shock_boundary_points=shock_points,
      pressure_ranges=pressure_ranges,
      pressure_ratios=pressure_ratios,
      message='terminal post-shock characteristic has no forward centerline margin',
    )
  forward_margins.append(terminal_forward_margin)
  nodes_list.append(
    MocCharacteristicNode(
      centerline_index=layer_index + 1,
      boundary_index=0,
      point_m=(float(centerline_point[0]), float(centerline_point[1])),
      state=centerline_result.state,
      point_result=centerline_result,
      total_pressure_Pa=terminal.total_pressure_Pa,
    )
  )
  ####

  closure_path = [fronts[0][-1]]
  closure_path.extend(front[-1] for front in fronts[1:])
  closure_path.append(
    _PostShockFrontSample(
      state=centerline_result.state,
      total_pressure_Pa=terminal.total_pressure_Pa,
    )
  )
  try:
    for index in range(1, len(closure_path) - 1):
      cells_list.append(
        MocCharacteristicCell(
          cell_index=len(cells_list),
          cell_kind='post-shock-centerline-closure',
          vertices_xr_m=(
            (closure_path[0].state.x_m, closure_path[0].state.y_m),
            (closure_path[index].state.x_m, closure_path[index].state.y_m),
            (closure_path[index + 1].state.x_m, closure_path[index + 1].state.y_m),
          ),
          centerline_indices=(layer_index,),
          boundary_indices=(index - 1, index),
        )
      )
  except ValueError as error:
    return _post_shock_field_failure(
      MocPostShockFieldStatus.GEOMETRY_FAILURE,
      characteristic_layer_count=layer_index,
      nodes=tuple(nodes_list),
      cells=tuple(cells_list),
      shock_boundary_points=shock_points,
      centerline_boundary_points=(shock_points[-1], centerline_point),
      terminal_centerline_state=centerline_result.state,
      pressure_ranges=pressure_ranges,
      pressure_ratios=pressure_ratios,
      message=f'post-shock centerline closure geometry failed: {error}',
    )
  ####

  cells = tuple(cells_list)
  topology = validate_moc_mesh(cells)
  if not topology.connected or not topology.forms_closed_zone or topology.nonmanifold_edge_count:
    return _post_shock_field_failure(
      MocPostShockFieldStatus.TOPOLOGY_FAILURE,
      characteristic_layer_count=layer_index,
      nodes=tuple(nodes_list),
      cells=cells,
      topology=topology,
      shock_boundary_points=shock_points,
      centerline_boundary_points=(shock_points[-1], centerline_point),
      terminal_centerline_state=centerline_result.state,
      maximum_geometry_residual_m=max(
        (abs(node.point_result.geometry_residual) for node in nodes_list if node.point_result.geometry_residual is not None),
        default=None,
      ),
      maximum_absolute_invariant_residual=max(
        (
          abs(value)
          for node in nodes_list
          for value in (node.point_result.invariant_residual_plus, node.point_result.invariant_residual_minus)
          if value is not None
        ),
        default=None,
      ),
      minimum_forward_margin_m=min(forward_margins, default=None),
      pressure_ranges=pressure_ranges,
      pressure_ratios=pressure_ratios,
      message=f'post-shock characteristic field topology failed: {topology.message}',
    )
  edge_counts = _mesh_edge_counts(cells, position_tolerance_m=position_tolerance_m)
  missing_shock_edges = [
    index
    for index, (first, second) in enumerate(zip(shock_points, shock_points[1:]))
    if (
      (edge := _mesh_edge_key(first, second, position_tolerance_m=position_tolerance_m)) not in edge_counts
      or edge_counts[edge] != 1
    )
  ]
  axis_edge = _mesh_edge_key(
    shock_points[-1],
    centerline_point,
    position_tolerance_m=position_tolerance_m,
  )
  if missing_shock_edges:
    return _post_shock_field_failure(
      MocPostShockFieldStatus.GEOMETRY_FAILURE,
      characteristic_layer_count=layer_index,
      nodes=tuple(nodes_list),
      cells=cells,
      topology=topology,
      shock_boundary_points=shock_points,
      centerline_boundary_points=(shock_points[-1], centerline_point),
      terminal_centerline_state=centerline_result.state,
      pressure_ranges=pressure_ranges,
      pressure_ratios=pressure_ratios,
      message=f'post-shock field is missing explicit shock boundary edge(s): {missing_shock_edges}',
    )
  if edge_counts.get(axis_edge, 0) != 1:
    return _post_shock_field_failure(
      MocPostShockFieldStatus.GEOMETRY_FAILURE,
      characteristic_layer_count=layer_index,
      nodes=tuple(nodes_list),
      cells=cells,
      topology=topology,
      shock_boundary_points=shock_points,
      centerline_boundary_points=(shock_points[-1], centerline_point),
      terminal_centerline_state=centerline_result.state,
      pressure_ranges=pressure_ranges,
      pressure_ratios=pressure_ratios,
      message='post-shock field is missing its explicit centerline boundary edge',
    )
  ####

  maximum_geometry_residual = max(
    (
      abs(node.point_result.geometry_residual)
      for node in nodes_list
      if node.point_result.geometry_residual is not None
    ),
    default=None,
  )
  maximum_invariant_residual = max(
    (
      abs(value)
      for node in nodes_list
      for value in (
        node.point_result.invariant_residual_plus,
        node.point_result.invariant_residual_minus,
      )
      if value is not None
    ),
    default=None,
  )
  return MocPostShockCharacteristicFieldResult(
    status=MocPostShockFieldStatus.CONVERGED_CLOSED,
    characteristic_layer_count=layer_index,
    nodes=tuple(nodes_list),
    cells=cells,
    topology=topology,
    shock_boundary_points_m=shock_points,
    centerline_boundary_points_m=(shock_points[-1], centerline_point),
    upstream_boundary_states=upstream_boundary_states,
    upstream_boundary_total_pressure_Pa=upstream_boundary_total_pressures,
    continuation_boundary_states=tuple(sample.state for sample in closure_path),
    continuation_boundary_total_pressure_Pa=tuple(
      sample.total_pressure_Pa for sample in closure_path
    ),
    terminal_centerline_state=centerline_result.state,
    maximum_geometry_residual_m=maximum_geometry_residual,
    maximum_absolute_invariant_residual=maximum_invariant_residual,
    minimum_forward_margin_m=min(forward_margins, default=None),
    upstream_total_pressure_range_Pa=pressure_ranges[0],
    downstream_total_pressure_range_Pa=pressure_ranges[1],
    minimum_post_shock_total_pressure_ratio=min(pressure_ratios),
    maximum_post_shock_total_pressure_ratio=max(pressure_ratios),
    physical_closure_status='closed-characteristic-fan',
    shock_closure_status='fitted-attached-shock',
    maximum_shock_angle_residual_rad=shock_fit.maximum_shock_angle_residual_rad,
    message=(
      'shock-seeded post-shock C+/C- characteristic field converged with '
      'explicit shock and centerline boundary edges'
    ),
    incoming_handoff_states=incoming_states,
    incoming_handoff_total_pressure_Pa=incoming_pressures,
    shock_boundary_states=tuple(sample.state for sample in samples),
    shock_boundary_total_pressure_Pa=tuple(
      sample.downstream_total_pressure_Pa for sample in samples
    ),
  )
