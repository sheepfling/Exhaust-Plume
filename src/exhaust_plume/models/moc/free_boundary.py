@dataclass(frozen=True, slots=True)
class MocFreeBoundaryShockResult:
  """A shock curve and post-shock field generated without prescribed points."""

  status: MocFreeBoundaryShockStatus
  shock_fit: MocShockBoundaryFitResult | None
  field: MocPostShockCharacteristicFieldResult | None
  shock_points_m: tuple[tuple[float, float], ...]
  upstream_states: tuple[CharacteristicState, ...]
  upstream_pressure_Pa: tuple[float, ...]
  downstream_flow_angles_rad: tuple[float, ...]
  shock_angle_residuals_rad: tuple[float, ...]
  maximum_shock_angle_residual_rad: float | None
  endpoint_m: tuple[float, float] | None
  message: str = ''
  normal_shock_terminal: MocNormalShockTerminalResult | None = None
  subsonic_shock_boundary: MocSubsonicShockBoundaryResult | None = None
  failed_sample_index: int | None = None
  failed_point_m: tuple[float, float] | None = None

  def __post_init__(self) -> None:
    if self.failed_sample_index is not None and (
      isinstance(self.failed_sample_index, bool)
      or not isinstance(self.failed_sample_index, int)
      or self.failed_sample_index < 0
    ):
      raise ValueError('failed_sample_index must be a nonnegative integer')
    if self.failed_point_m is not None:
      if len(self.failed_point_m) != 2 or not all(
        isfinite(float(value)) for value in self.failed_point_m
      ):
        raise ValueError('failed_point_m must contain two finite coordinates')
      object.__setattr__(
        self,
        'failed_point_m',
        (float(self.failed_point_m[0]), float(self.failed_point_m[1])),
      )
    if (self.failed_sample_index is None) != (self.failed_point_m is None):
      raise ValueError(
        'failed_sample_index and failed_point_m must be supplied together'
      )

  @property
  def converged(self) -> bool:
    return self.status is MocFreeBoundaryShockStatus.CONVERGED_FIELD
  ####

  @property
  def physical_closure_verified(self) -> bool:
    return self.converged and self.field is not None and self.field.physical_closure_verified
  ####

  @property
  def subsonic_terminal_required(self) -> bool:
    """Whether the supersonic MOC lane reached a normal-shock boundary."""

    return self.status is MocFreeBoundaryShockStatus.SUBSONIC_TERMINAL_REQUIRED
  ####

  @property
  def sample_count(self) -> int:
    return len(self.shock_points_m)
  ####

  @property
  def field_status(self) -> MocPostShockFieldStatus | None:
    return None if self.field is None else self.field.status
  ####

  @property
  def terminal_model_verified(self) -> bool:
    """Whether a typed normal-shock terminal was reconstructed."""

    return self.normal_shock_terminal is not None and self.normal_shock_terminal.converged
  ####

  @property
  def subsonic_boundary_verified(self) -> bool:
    """Whether a positioned attached-shock subsonic seam was retained."""

    return (
      self.subsonic_shock_boundary is not None
      and self.subsonic_shock_boundary.converged
      and self.subsonic_shock_boundary.subsonic
    )
  ####

  def as_report(self) -> dict[str, object]:
    return {
      'status': self.status.value,
      'converged': self.converged,
      'physical_closure_verified': self.physical_closure_verified,
      'subsonic_terminal_required': self.subsonic_terminal_required,
      'sample_count': self.sample_count,
      'endpoint_m': self.endpoint_m,
      'maximum_shock_angle_residual_rad': self.maximum_shock_angle_residual_rad,
      'field_status': None if self.field_status is None else self.field_status.value,
      'subsonic_boundary_verified': self.subsonic_boundary_verified,
      'subsonic_shock_boundary': (
        None
        if self.subsonic_shock_boundary is None
        else self.subsonic_shock_boundary.as_report()
      ),
      'normal_shock_terminal': (
        None
        if self.normal_shock_terminal is None
        else self.normal_shock_terminal.as_report()
      ),
      'failed_sample_index': self.failed_sample_index,
      'failed_point_m': self.failed_point_m,
      'message': self.message,
    }
