def _characteristic_invariant_value(
  family: CharacteristicFamily,
  theta_rad: float,
  mach: float,
  gamma: float,
) -> float:
  nu = prandtl_meyer_angle_rad(mach, gamma)
  return theta_rad - nu if family is CharacteristicFamily.PLUS else theta_rad + nu
